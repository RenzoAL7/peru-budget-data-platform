class SchemaDriftError(RuntimeError):
    """El archivo de origen ya no cumple el contrato de columnas."""


def validate_header(columns: list[str]) -> None:
    """Falla si faltan columnas o aparecen columnas nuevas."""
    found = [c.strip().strip('"').upper() for c in columns]
    missing = sorted(set(EXPECTED_COLUMNS) - set(found))
    extra = sorted(set(found) - set(EXPECTED_COLUMNS))
    if missing or extra:
        raise SchemaDriftError(f"Cambio de esquema. Faltan: {missing}. Nuevas: {extra}.")
